// Builds both halves of the connection test.
//   docs/spike/                      -> GitHub Pages copy of the Owlbear extension
//   spike/dist/owlbear-bridge-spike/ -> Obsidian plugin to copy into .obsidian/plugins/
import { build } from "esbuild";
import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const pagesDir = join(root, "..", "docs", "spike");
const pluginDir = join(root, "dist", "owlbear-bridge-spike");

const PAGES_BASE = "https://gizmo73.github.io/owlbear-obsidian-bestiary/spike/";
const LOCAL_BASE = "http://127.0.0.1:27190/ext/";

function manifest(base, label) {
  return JSON.stringify(
    {
      name: `Obsidian Bridge Test (${label})`,
      version: "0.0.1",
      manifest_version: 1,
      action: {
        title: `Obsidian Bridge Test (${label})`,
        icon: `${base}icon.svg`,
        popover: `${base}index.html`,
        width: 380,
        height: 560,
      },
      icon: `${base}icon.svg`,
      author: "Gizmo73",
      homepage_url: "https://github.com/Gizmo73/owlbear-obsidian-bestiary",
      description: "Throwaway connection test between Owlbear Rodeo and an Obsidian plugin",
    },
    null,
    2,
  );
}

// 1. Extension bundle (shared by both copies).
const ext = await build({
  entryPoints: [join(root, "extension", "src", "app.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  write: false,
  logLevel: "warning",
});
const appJs = ext.outputFiles[0].text;
const indexHtml = await readFile(join(root, "extension", "index.html"), "utf8");
const iconSvg = await readFile(join(root, "extension", "icon.svg"), "utf8");

// 2. GitHub Pages copy.
await mkdir(pagesDir, { recursive: true });
await writeFile(join(pagesDir, "app.js"), appJs);
await writeFile(join(pagesDir, "index.html"), indexHtml);
await writeFile(join(pagesDir, "icon.svg"), iconSvg);
await writeFile(join(pagesDir, "manifest.json"), manifest(PAGES_BASE, "GitHub Pages"));
await writeFile(join(root, "..", "docs", ".nojekyll"), "");

// 3. Obsidian-served copy, embedded into the plugin.
const files = {
  "manifest.json": { type: "application/json", body: manifest(LOCAL_BASE, "Obsidian") },
  "index.html": { type: "text/html; charset=utf-8", body: indexHtml },
  "app.js": { type: "text/javascript; charset=utf-8", body: appJs },
  "icon.svg": { type: "image/svg+xml", body: iconSvg },
};
await writeFile(
  join(root, "plugin", "src", "embedded.gen.ts"),
  `// Generated by build.mjs - do not edit.\nimport type { StaticFile } from "./server";\nexport const EXTENSION_FILES: Record<string, StaticFile> = ${JSON.stringify(files)};\n`,
);

// 4. Obsidian plugin bundle.
await mkdir(pluginDir, { recursive: true });
await build({
  entryPoints: [join(root, "plugin", "src", "main.ts")],
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "es2020",
  external: ["obsidian", "electron", "bufferutil", "utf-8-validate"],
  outfile: join(pluginDir, "main.js"),
  logLevel: "warning",
});
await copyFile(join(root, "plugin", "manifest.json"), join(pluginDir, "manifest.json"));

console.log("built docs/spike/ and spike/dist/owlbear-bridge-spike/");
